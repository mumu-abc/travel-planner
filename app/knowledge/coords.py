def get_city_coords(destination: str) -> tuple[float, float] | None:
    """
    根据目的地名称获取城市中心坐标。

    先精确匹配，再模糊匹配（包含关系）。
    """
    city = destination.split(",")[0].strip()
    if city in CITY_COORDS:
        return CITY_COORDS[city]
    # 模糊匹配
    for key, coords in CITY_COORDS.items():
        if key in city or city in key:
            return coords
    return None
